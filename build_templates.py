"""Bundle templates/*.html and public/style.css into templates_bundle.py.

Vercel always ships .py files, so this guarantees the pages exist online even if
the templates folder isn't packaged. Run it again after you edit a template or the CSS:

    python build_templates.py
"""
from pathlib import Path

base = Path(__file__).parent
templates = {p.name: p.read_text(encoding="utf-8") for p in sorted((base / "templates").glob("*.html"))}
css = (base / "public" / "style.css").read_text(encoding="utf-8")

out = ['"""Generated by build_templates.py - do not edit by hand."""', "", "TEMPLATES = {"]
for name, source in templates.items():
    out.append(f"    {name!r}: {source!r},")
out += ["}", "", f"STYLE_CSS = {css!r}", ""]
(base / "templates_bundle.py").write_text("\n".join(out), encoding="utf-8")
print(f"Bundled {len(templates)} templates + style.css into templates_bundle.py")
